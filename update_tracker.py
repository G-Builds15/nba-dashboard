#!/usr/bin/env python3
"""
update_tracker.py
Appends today's best bets from slate_data.js to tracker.json.
Parlay pieces are tracked individually — no combined parlay slips.
Each run also settles older Pending picks (Win / Loss / Push) from ESPN final scores and
player game logs, with profit/loss in units (flat 1u per pick).
"""

import argparse
import json
import os
import re
import subprocess
import sys
import unicodedata
from datetime import datetime, timedelta, timezone

parser = argparse.ArgumentParser()
parser.add_argument('--outdir', default=os.path.dirname(os.path.abspath(__file__)))
args = parser.parse_args()
OUTDIR = args.outdir

# Use fixed UTC offsets: EDT (summer) = -4, EST (winter) = -5
# NBA season spans both; pick the correct offset for today's wall-clock date
_now_utc = datetime.now(timezone.utc)
_naive   = _now_utc.replace(tzinfo=None)
# DST in US: 2nd Sun Mar → 1st Sun Nov
def _is_edt(dt):
    year = dt.year
    # 2nd Sunday in March
    mar = datetime(year, 3, 8)
    mar_sun = mar + timedelta(days=(6 - mar.weekday()) % 7)
    # 1st Sunday in November
    nov = datetime(year, 11, 1)
    nov_sun = nov + timedelta(days=(6 - nov.weekday()) % 7)
    return mar_sun <= dt.replace(tzinfo=None) < nov_sun
ET = timezone(timedelta(hours=-4 if _is_edt(_naive) else -5))
TODAY_ET = datetime.now(ET).strftime('%Y-%m-%d')

TRACKER_FILE  = os.path.join(OUTDIR, 'tracker.json')
SLATE_JS_FILE = os.path.join(OUTDIR, 'slate_data.js')

def load_tracker():
    if not os.path.exists(TRACKER_FILE):
        return {'picks': []}
    with open(TRACKER_FILE) as f:
        try:
            return json.load(f)
        except Exception:
            return {'picks': []}

def write_tracker(data):
    with open(TRACKER_FILE, 'w') as f:
        json.dump(data, f, indent=2)
    print(f'[tracker] wrote {TRACKER_FILE}')

def load_slate_from_js():
    """Extract SLATE_DATA JSON from slate_data.js."""
    if not os.path.exists(SLATE_JS_FILE):
        print(f'[tracker] missing {SLATE_JS_FILE}', file=sys.stderr)
        return None
    with open(SLATE_JS_FILE) as f:
        content = f.read()
    # Strip JS variable assignment wrapper
    match = re.search(r'const SLATE_DATA\s*=\s*(\{.*\})\s*;', content, re.DOTALL)
    if not match:
        print('[tracker] could not parse SLATE_DATA from slate_data.js', file=sys.stderr)
        return None
    try:
        return json.loads(match.group(1))
    except Exception as e:
        print(f'[tracker] JSON parse error: {e}', file=sys.stderr)
        return None

def write_slate_js(slate):
    """Rewrite slate_data.js (same format slate_builder writes) so the dashboard's embedded tracker is current."""
    with open(SLATE_JS_FILE, 'w') as f:
        f.write('// Auto-generated by slate_builder.py — do not edit manually\n')
        f.write('const SLATE_DATA = ')
        json.dump(slate, f, indent=2)
        f.write(';\n')

def format_pick_label(p):
    """Format a prop pick into a readable tracker label."""
    player    = p.get('player_name', '')
    direction = p.get('direction', '')
    line      = p.get('line', '')
    label     = p.get('prop_label', '')
    return f"{player} {direction} {line} {label}".strip()


# ── settlement (ESPN finals + player game logs) ───────────────────────────────
ESPN_SEASON = (datetime.now(ET).year + 1) if datetime.now(ET).month >= 10 else datetime.now(ET).year
ESPN_SITE   = 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba'
ESPN_COMMON = 'https://site.web.api.espn.com/apis/common/v3/sports/basketball/nba'
UA          = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/124 Safari/537.36'
RULES = 'top-v1'             # bump to archive the visible record when pick-selection rules change
VOID_AFTER_DAYS = 3          # a prop whose player never shows in the log is voided (Push) after this

def get_json(url):
    try:
        r = subprocess.run(['curl', '-s', '-L', '--max-time', '25', '-H', f'User-Agent: {UA}', url],
                           capture_output=True, text=True, timeout=30)
        return json.loads(r.stdout) if r.stdout else None
    except Exception as e:
        print(f'[tracker] fetch failed {url[:90]}: {e}', file=sys.stderr)
        return None

def norm_player(name):
    n = unicodedata.normalize('NFKD', name or '').encode('ascii', 'ignore').decode().lower().strip()
    n = n.replace('.', '').replace("'", '').replace(',', '').replace('-', ' ')
    parts = [x for x in n.split() if x]
    while parts and parts[-1] in {'jr', 'sr', 'ii', 'iii', 'iv', 'v'}:
        parts.pop()
    return ' '.join(parts)

def num(v):
    if isinstance(v, dict):
        v = v.get('value', v.get('displayValue'))
    try:
        return float(str(v).replace(',', ''))
    except (TypeError, ValueError):
        return None

def profit(result, odds):
    """Units won/lost on a flat 1u stake at American odds."""
    if result == 'Push':
        return 0.0
    if result == 'Loss':
        return -1.0
    try:
        o = float(odds)
    except (TypeError, ValueError):
        return 0.0
    if o == 0:
        return 0.0
    return round(o / 100 if o > 0 else 100 / abs(o), 2)

def verdict(value, line, direction):
    """Win/Loss/Push for Over/Under against a line."""
    if value is None or line is None:
        return None
    if value == line:
        return 'Push'
    return 'Win' if ((value > line) == (direction == 'Over')) else 'Loss'

_finals_cache = {}
def finals_for(date_str):
    """{frozenset({home_full, away_full}): {full_name: score}} for completed games on an ET date.
    Queries the day itself and the next day separately (late games can be filed under either), retries a
    failed fetch, and never caches an empty or failed result, so one bad response cannot block settling."""
    if date_str in _finals_cache:
        return _finals_cache[date_str]
    d0 = datetime.strptime(date_str, '%Y-%m-%d')
    out, ok = {}, True
    for off in (0, 1):
        day = (d0 + timedelta(days=off)).strftime('%Y%m%d')
        data = None
        for _ in range(3):
            data = get_json(f'{ESPN_SITE}/scoreboard?dates={day}&limit=200')
            if data and 'events' in data:
                break
        if not data or 'events' not in data:
            ok = False
            print(f'[tracker] scoreboard {day} unavailable', file=sys.stderr)
            continue
        for ev in data.get('events', []):
            comp = (ev.get('competitions') or [{}])[0]
            st = (comp.get('status') or {}).get('type') or {}
            cs = comp.get('competitors') or []
            if len(cs) != 2 or not (st.get('completed') or st.get('state') == 'post'):
                continue
            try:
                scores = {c['team']['displayName']: num(c.get('score')) for c in cs}
            except Exception:
                continue
            if None in scores.values():
                continue
            out[frozenset(scores)] = scores
    print(f'[tracker] finals for {date_str}: {len(out)} completed games')
    if ok and out:
        _finals_cache[date_str] = out
    return out

_player_ids = None
def player_id(name):
    global _player_ids
    if _player_ids is None:
        _player_ids = {}
        try:
            with open(os.path.join(OUTDIR, 'raw_player_stats.json')) as f:
                rs = json.load(f)['resultSets'][0]
            h = rs['headers']
            for row in rs['rowSet']:
                r = dict(zip(h, row))
                _player_ids[norm_player(r.get('PLAYER_NAME'))] = r.get('PLAYER_ID')
        except Exception as e:
            print(f'[tracker] no player id table ({e}); props cannot be settled this run', file=sys.stderr)
    return _player_ids.get(norm_player(name))

_gamelogs = {}
def game_stat(pick_date, meta):
    """The player's stat line for the game on pick_date, or None if not in the log yet."""
    pid = player_id(meta.get('player'))
    if not pid:
        return None
    if pid not in _gamelogs:
        _gamelogs[pid] = get_json(f'{ESPN_COMMON}/athletes/{pid}/gamelog?region=us&lang=en&contentorigin=espn'
                                  f'&season={ESPN_SEASON}') or {}
    d = _gamelogs[pid]
    idx = {n: i for i, n in enumerate(d.get('names', []))}
    need = ('minutes', 'points', 'totalRebounds', 'assists', 'threePointFieldGoalsMade-threePointFieldGoalsAttempted')
    if any(k not in idx for k in need):
        return None
    start = datetime.strptime(pick_date, '%Y-%m-%d').replace(tzinfo=ET)
    end   = start + timedelta(days=1)
    meta_ev = d.get('events') or {}
    total_events = dated_events = 0
    for st in d.get('seasonTypes', []):
        if 'regular' not in (st.get('displayName') or '').lower():
            continue
        for cat in st.get('categories', []):
            for e in cat.get('events', []):
                m = meta_ev.get(str(e.get('eventId'))) or {}
                gd = m.get('gameDate')
                total_events += 1
                dated_events += 1 if gd else 0
                hit = False
                if gd:
                    try:
                        hit = start <= datetime.fromisoformat(gd.replace('Z', '+00:00')) < end
                    except ValueError:
                        hit = False
                elif (m.get('opponent') or {}).get('displayName') == meta.get('opp_full'):
                    hit = True
                if not hit:
                    continue
                s = e.get('stats') or []
                try:
                    mins = num(s[idx['minutes']]) or 0
                    f3 = num(str(s[idx['threePointFieldGoalsMade-threePointFieldGoalsAttempted']]).split('-')[0])
                    return {'min': mins, 'pts': num(s[idx['points']]), 'reb': num(s[idx['totalRebounds']]),
                            'ast': num(s[idx['assists']]), '3pm': f3}
                except IndexError:
                    return None
    # Not found. {} = the log is trustworthy (dated games, or no games) and this game isn't in it;
    # None = cannot tell (no game dates in the log), so the pick stays Pending.
    return {} if (total_events == 0 or dated_events > 0) else None

def settle_pick(pick):
    """Return 'Win'/'Loss'/'Push' or None (leave Pending)."""
    meta = pick.get('meta') or {}
    kind = meta.get('kind')
    date = pick.get('date')
    if not kind or not date:
        return None
    if kind in ('spread', 'total', 'ml'):
        game = finals_for(date).get(frozenset({meta.get('home_full'), meta.get('away_full')}))
        if not game:
            print(f"[tracker] no final found for {meta.get('away_full')} @ {meta.get('home_full')} on {date}", file=sys.stderr)
            return None
        if kind == 'ml':
            mine, theirs = game.get(meta.get('team_full')), game.get(meta.get('opp_full'))
            if mine is None or theirs is None or mine == theirs:
                return None
            return 'Win' if mine > theirs else 'Loss'
        if kind == 'spread':
            mine, theirs = game.get(meta.get('team_full')), game.get(meta.get('opp_full'))
            if mine is None or theirs is None:
                return None
            return verdict(mine + meta['line'] - theirs, 0, 'Over')       # covers if margin + line > 0
        return verdict(sum(game.values()), meta.get('line'), meta.get('direction'))
    # props
    stat = game_stat(date, meta)
    if stat is None:
        return None
    if not stat:
        age = (datetime.now(ET).date() - datetime.strptime(date, '%Y-%m-%d').date()).days
        return 'Push' if age >= VOID_AFTER_DAYS else None                 # never played -> prop voided
    if stat['min'] <= 0:
        return 'Push'                                                       # DNP -> voided
    pt = meta.get('prop_type')
    value = (stat['pts'] + stat['reb'] + stat['ast']) if pt == 'pra' else stat.get(pt)
    return verdict(value, meta.get('line'), meta.get('direction'))

TEAM_FULL = {
    'ATL': 'Atlanta Hawks', 'BOS': 'Boston Celtics', 'BKN': 'Brooklyn Nets', 'CHA': 'Charlotte Hornets',
    'CHI': 'Chicago Bulls', 'CLE': 'Cleveland Cavaliers', 'DAL': 'Dallas Mavericks', 'DEN': 'Denver Nuggets',
    'DET': 'Detroit Pistons', 'GSW': 'Golden State Warriors', 'HOU': 'Houston Rockets', 'IND': 'Indiana Pacers',
    'LAC': 'LA Clippers', 'LAL': 'Los Angeles Lakers', 'MEM': 'Memphis Grizzlies', 'MIA': 'Miami Heat',
    'MIL': 'Milwaukee Bucks', 'MIN': 'Minnesota Timberwolves', 'NOP': 'New Orleans Pelicans',
    'NYK': 'New York Knicks', 'OKC': 'Oklahoma City Thunder', 'ORL': 'Orlando Magic',
    'PHI': 'Philadelphia 76ers', 'PHX': 'Phoenix Suns', 'POR': 'Portland Trail Blazers',
    'SAC': 'Sacramento Kings', 'SAS': 'San Antonio Spurs', 'TOR': 'Toronto Raptors',
    'UTA': 'Utah Jazz', 'WAS': 'Washington Wizards',
}

def legacy_meta(pick):
    """Rebuild settlement details for picks logged before 'meta' existed, from the pick label."""
    label, typ = pick.get('pick', ''), pick.get('type', '')
    try:
        if typ in ('spread', 'total'):
            m = re.match(r'^(\S+)\s+(\S+)\s+\((\w+) @ (\w+) (?:spread|total)\)$', label)
            if not m:
                return None
            first, second, away, home = m.groups()
            hf, af = TEAM_FULL.get(home), TEAM_FULL.get(away)
            if not (hf and af):
                return None
            if typ == 'total':
                return {'kind': 'total', 'direction': first, 'line': float(second), 'home_full': hf, 'away_full': af}
            team_home = first == home
            return {'kind': 'spread', 'line': float(second),
                    'team_full': hf if team_home else af, 'opp_full': af if team_home else hf,
                    'home_full': hf, 'away_full': af}
        m = re.match(r'^(.*?)\s+(Over|Under)\s+([\d.]+)\s+(.*)$', label)
        if not m:
            return None
        return {'kind': 'prop', 'player': m.group(1), 'direction': m.group(2),
                'line': float(m.group(3)), 'prop_type': typ}
    except (ValueError, TypeError):
        return None

def pick_key(p):
    """One pick per day per market: (date, game, 'total'/'spread') or (date, player, stat).
    A line move or a flipped direction on a later run does not create a second pick."""
    label, typ, date = p.get('pick', ''), p.get('type', ''), p.get('date', '')
    if typ in ('spread', 'total', 'moneyline'):
        m = re.search(r'\((\w+) @ (\w+) (?:spread|total|moneyline)\)', label)
        return (date, typ, m.group(1) + '@' + m.group(2) if m else label)
    m = re.match(r'^(.*?)\s+(Over|Under)\s+[\d.]+\s+', label)
    return (date, typ, norm_player(m.group(1)) if m else label)

def dedupe(tracker):
    """Drop later duplicates (keep the first logged). Returns how many were removed."""
    seen, keep = set(), []
    for p in tracker.get('picks', []):
        k = pick_key(p)
        if k in seen:
            continue
        seen.add(k)
        keep.append(p)
    removed = len(tracker.get('picks', [])) - len(keep)
    tracker['picks'] = keep
    return removed

def settle_pending(tracker):
    changed = 0
    for pick in tracker.get('picks', []):
        if pick.get('result') not in (None, 'Pending'):
            continue
        if not pick.get('meta'):
            pick['meta'] = legacy_meta(pick)           # picks logged before settlement existed
        if not pick.get('meta') or (pick.get('date') or '9999') > TODAY_ET:
            continue
        try:
            res = settle_pick(pick)
        except Exception as e:
            print(f"[tracker] could not settle '{pick.get('pick')}': {e}", file=sys.stderr)
            continue
        if res:
            pick['result'] = res
            pick['pl'] = profit(res, pick.get('odds'))
            changed += 1
    return changed

def spread_meta(g):
    """meta for a spread pick, parsed from the lean ('BOS -4.5')."""
    try:
        abbr, line = g['lean_spread'].split()
        home = abbr == g.get('home_abbr')
        return {'kind': 'spread', 'line': float(line),
                'team_full': g['home_full'] if home else g['away_full'],
                'opp_full':  g['away_full'] if home else g['home_full'],
                'home_full': g['home_full'], 'away_full': g['away_full']}
    except Exception:
        return None

def ml_meta(g):
    lean = g.get('lean_ml')
    try:
        home = lean == g.get('home_abbr')
        return {'kind': 'ml', 'team_full': g['home_full'] if home else g['away_full'],
                'opp_full': g['away_full'] if home else g['home_full'],
                'home_full': g['home_full'], 'away_full': g['away_full']}
    except KeyError:
        return None

def total_meta(g):
    try:
        direction, line = g['lean_total'].split()
        return {'kind': 'total', 'direction': direction, 'line': float(line),
                'home_full': g['home_full'], 'away_full': g['away_full']}
    except Exception:
        return None

if __name__ == '__main__':
    slate = load_slate_from_js()
    if not slate:
        print('[tracker] no slate data, skipping.')
        sys.exit(0)

    slate_date = slate.get('slate_date', TODAY_ET)
    games = slate.get('games', [])

    tracker = load_tracker()

    # One-time reset when the pick-selection rules change: settle what can be settled, move the old picks to
    # tracker_archive.json (nothing is deleted), and start the visible record fresh under the new rules.
    migrated = False
    if tracker.get('rules') != RULES:
        settle_pending(tracker)
        old = tracker.get('picks', [])
        if old:
            arch_path = os.path.join(OUTDIR, 'tracker_archive.json')
            try:
                with open(arch_path) as f:
                    arch = json.load(f)
            except Exception:
                arch = {'picks': []}
            arch.setdefault('picks', []).extend(old)
            with open(arch_path, 'w') as f:
                json.dump(arch, f, indent=1)
            print(f'[tracker] archived {len(old)} earlier picks to tracker_archive.json')
        tracker = {'rules': RULES, 'archived': tracker.get('archived', 0) + len(old), 'picks': []}
        migrated = True

    removed = dedupe(tracker)
    if removed:
        print(f'[tracker] removed {removed} duplicate pick(s) (line moves / flipped direction)')
    existing_picks = {pick_key(p) for p in tracker.get('picks', [])}

    new_picks = []
    now_utc = datetime.now(timezone.utc)

    def started(g):
        """True once tip-off has passed: odds may be in-play, so such a game is never logged."""
        try:
            return datetime.fromisoformat(str(g.get('commence_time', '')).replace('Z', '+00:00')) <= now_utc
        except ValueError:
            return False

    skipped_started = 0
    for g in games:
        if started(g):
            skipped_started += 1
            continue
        away = g.get('away_abbr', '')
        home = g.get('home_abbr', '')
        game_label = f"{away} @ {home}"

        # Best bet game leans
        if g.get('best_bet_spread') and g.get('lean_spread'):
            label = f"{g['lean_spread']} ({game_label} spread)"
            cand = {'date': slate_date, 'pick': label, 'type': 'spread'}
            if pick_key(cand) not in existing_picks:
                existing_picks.add(pick_key(cand))
                new_picks.append({
                    'date':     slate_date,
                    'pick':     label,
                    'odds':     g.get('odds_spread'),
                    'grade':    g.get('grade_spread'),
                    'type':     'spread',
                    'result':   'Pending',
                    'pl':       None,
                    'meta':     spread_meta(g),
                })

        if g.get('best_bet_ml') and g.get('lean_ml'):
            label = f"{g['lean_ml']} ML ({game_label} moneyline)"
            cand = {'date': slate_date, 'pick': label, 'type': 'moneyline'}
            if pick_key(cand) not in existing_picks:
                existing_picks.add(pick_key(cand))
                new_picks.append({
                    'date':     slate_date,
                    'pick':     label,
                    'odds':     g.get('odds_ml'),
                    'grade':    g.get('grade_ml'),
                    'type':     'moneyline',
                    'result':   'Pending',
                    'pl':       None,
                    'meta':     ml_meta(g),
                })

        if g.get('best_bet_total') and g.get('lean_total'):
            label = f"{g['lean_total']} ({game_label} total)"
            cand = {'date': slate_date, 'pick': label, 'type': 'total'}
            if pick_key(cand) not in existing_picks:
                existing_picks.add(pick_key(cand))
                new_picks.append({
                    'date':     slate_date,
                    'pick':     label,
                    'odds':     g.get('odds_total'),
                    'grade':    g.get('grade_total'),
                    'type':     'total',
                    'result':   'Pending',
                    'pl':       None,
                    'meta':     total_meta(g),
                })

        # Best bet props (graded individually)
        for p in g.get('props', []):
            if not p.get('best_bet'):
                continue
            label = format_pick_label(p)
            cand = {'date': slate_date, 'pick': label, 'type': p.get('prop_type', 'prop')}
            if pick_key(cand) not in existing_picks:
                existing_picks.add(pick_key(cand))
                player_team_home = p.get('team') == home
                new_picks.append({
                    'date':     slate_date,
                    'pick':     label,
                    'odds':     p.get('odds'),
                    'grade':    p.get('grade'),
                    'type':     p.get('prop_type', 'prop'),
                    'result':   'Pending',
                    'pl':       None,
                    'meta':     {'kind': 'prop', 'player': p.get('player_name'), 'prop_type': p.get('prop_type'),
                                 'line': p.get('line'), 'direction': p.get('direction'),
                                 'opp_full': g.get('away_full') if player_team_home else g.get('home_full')},
                })

    if skipped_started:
        print(f'[tracker] skipped {skipped_started} game(s) already started (live odds are never logged)')
    if new_picks:
        tracker.setdefault('picks', []).extend(new_picks)
        print(f'[tracker] added {len(new_picks)} new picks for {slate_date}')
    else:
        print(f'[tracker] no new picks for {slate_date} (already logged or none)')

    pending = sum(1 for p in tracker.get('picks', []) if p.get('result') in (None, 'Pending'))
    settled = settle_pending(tracker)
    print(f'[tracker] settled {settled} pick(s); {pending - settled} still pending')

    if new_picks or settled or removed or migrated or not os.path.exists(TRACKER_FILE):
        write_tracker(tracker)

    # Always sync the embedded tracker, then build.py inlines the up-to-date slate
    slate['tracker'] = tracker
    write_slate_js(slate)
